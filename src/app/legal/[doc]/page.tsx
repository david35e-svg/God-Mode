type P = { params: Promise<{ doc: string }> };
export const generateStaticParams = () => Object.keys(DOCS).map((doc) => ({ doc }));
export async function generateMetadata({ params }: P): Promise<Metadata> {
  return { title: DOCS[(await params).doc]?.title };
}

export default async function Page({ params }: P) {
  const d = DOCS[(await params).doc];
  if (!d) notFound();
  return (
    <article className="wrap section prose narrow">
      <h1 className="title-xl">{d.title}.</h1>
      {d.intro && <p className="lead">{d.intro}</p>}
      {d.draft && <p className="draft">טיוטה שממתינה לבדיקת עורך דין. אין לראות בה ייעוץ משפטי.</p>}
      {d.body.map(([h, p]) => (
        <section key={h}>
          <h2 className="title-m">{h}</h2>
          <p>
            {p.includes("<מדיניות הקוקיז>")
              ? <>פירוט מלא נמצא ב<Link href="/legal/cookies">מדיניות הקוקיז</Link>.</>
              : p}
          </p>
        </section>
      ))}
      <nav className="legal-nav" aria-label="מסמכים נוספים">
        {Object.entries(DOCS).filter(([k]) => k !== (d.title && Object.keys(DOCS).find((x) => DOCS[x] === d))).map(([k, v]) => (
          <Link key={k} href={`/legal/${k}`}>{v.title}</Link>
        ))}
      </nav>
    </article>
  );
}
